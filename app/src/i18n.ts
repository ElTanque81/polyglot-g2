const NAMES: Record<string, [string, string]> = {
  ar: ['Arabic', 'Arabisch'], hi: ['Hindi', 'Hindi'], he: ['Hebrew', 'Hebräisch'], fa: ['Persian', 'Persisch'], ur: ['Urdu', 'Urdu'],
  th: ['Thai', 'Thailändisch'], bn: ['Bengali', 'Bengalisch'], es: ['Spanish', 'Spanisch'], ru: ['Russian', 'Russisch'],
  zh: ['Chinese', 'Chinesisch'], en: ['English', 'Englisch'], de: ['German', 'Deutsch'], fr: ['French', 'Französisch'],
}
/** Name of a language in the UI language (falls back to the code). */
export const langName = (code: string) => NAMES[code]?.[current === 'de' ? 1 : 0] ?? code.toUpperCase()

let current: Lang = 'en'
export const setLang = (l: Lang) => { current = l }
